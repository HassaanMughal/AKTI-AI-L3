"""## Step 12: Classical Computer Vision Fallback
If YOLO bounding box labels are currently unavailable, classical Computer Vision techniques can be utilized as a baseline for plate localization. This function uses bilateral filtering, edge detection (Canny), and contour analysis to find plate-like rectangular regions.
"""

# Get test images
test_images = sorted(list((det_dataset_path / "images/test").glob("*.*")))
sample_images = random.sample(test_images, k=min(6, len(test_images)))

def find_plate(image):
    """
    Detect rectangular plate-like regions using basic edge detection
    and contour filtering.
    """
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    gray = cv2.bilateralFilter(gray, 11, 17, 17)
    edges = cv2.Canny(gray, 30, 200)

    contours, _ = cv2.findContours(edges.copy(), cv2.RETR_TREE, cv2.CHAIN_APPROX_SIMPLE)
    contours = sorted(contours, key=cv2.contourArea, reverse=True)[:10]

    boxes = []
    for c in contours:
        perimeter = cv2.arcLength(c, True)
        approx = cv2.approxPolyDP(c, 0.02 * perimeter, True)

        # Check for rectangular contour
        if len(approx) == 4:
            x, y, w, h = cv2.boundingRect(approx)

            # Basic size filter
            if w > 60 and h > 15:
                boxes.append((x, y, x + w, y + h))

    return boxes

# Visualize results
plt.figure(figsize=(12, 8))

for i, img_path in enumerate(sample_images):
    image = cv2.imread(str(img_path))
    boxes = find_plate(image)

    # Draw the first candidate box (if any)
    if boxes:
        x1, y1, x2, y2 = boxes[0]
        cv2.rectangle(image, (x1, y1), (x2, y2), (0, 255, 0), 2)

